# 对齐原理小实验 —— 看不懂 :<10 就运行这个文件，一行行看输出
#
# 关键一句话：:<10 不是"加空格"，而是"给这段内容划一个固定宽度的区域（10 格）"。
# 内容短就自动补空格填满，内容长就原样伸出格子。目的只有一个：让后面的列从同一位置开始。

# 把空格变成 · 显示出来，不然看不见
def show(s):
    return s.replace(" ", "·")


a = "Li"      # 2 个字
b = "Wang"    # 4 个字

print("=" * 56)
print("① 不管对齐，直接打印")
print("=" * 56)
print(show(f"{a}|88.5"))
print(show(f"{b}|92.0"))
print("→ 竖线 | 的位置不一样，第二列歪了。")
print("   因为 Li 占 2 格、Wang 占 4 格，后面的内容就跟着往前/往后跑。")
print()

print("=" * 56)
print("② 加上 :<10 —— 第一列统一划成 10 格")
print("=" * 56)
print(show(f"{a:<10}|88.5"))
print(show(f"{b:<10}|92.0"))
print("→ 竖线 | 对齐了。短的那个被自动补了空格，撑满 10 格。")
print()

print("=" * 56)
print("③ 数一数，第一列到底几格")
print("=" * 56)
print(f'   不加 :<10 → "Li"   = {len(a)} 格')
print(f'   不加 :<10 → "Wang" = {len(b)} 格')
print("   —— 一个 2 格一个 4 格，这就是歪的原因")
print()
print(f'   加了 :<10 → "Li"   = {len(f"{a:<10}")} 格')
print(f'   加了 :<10 → "Wang" = {len(f"{b:<10}")} 格')
print("   —— 都是 10 格，所以后面的列对得齐")
print()

print("=" * 56)
print("④ 宽度比内容还小会怎样（:<4，但 Wang 有 4 格）")
print("=" * 56)
print(f'   "{show(f"{b:<4}")}" = {len(f"{b:<4}")} 格')
print("→ 内容不会被切掉，只是不补空格了。")
print("   所以宽度是『至少占这么多』，不是『最多显示这么多』。")
print()

print("=" * 56)
print("⑤ 换回你的作业：张三 / 李四（都是 2 个字）")
print("=" * 56)
print(f"{'姓名':<10}{'成绩':>6}")
print(f"{'张三':<10}{88.5:>6.1f}")
print(f"{'李四':<10}{92.0:>6.1f}")
print()
print("→ 外面看不出空格，但第一列每行都是 10 格，第二列自然排成一条竖线。")
print()
print("⚠️ 中文的坑：屏幕上中文一个字占 2 格宽，但 :<10 是按『字符个数』数格子。")
print("   所以『张三』和『王小明』长度都是 2 和 3 个字符，补完空格后列数一样，")
print("   但屏幕上宽度不同，还是会错开一列。你没看错——这是 Python 本身的老问题。")
