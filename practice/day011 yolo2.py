# 这是你第一次真正训练一个神经网络。四个参数先搞懂再敲:
#
#   data    = "data/NEU-DET-yolo/data.yaml"   去哪找数据和类别表
#   model   = "yolov8n.pt"                    从哪份权重开始(n=nano,最小的)
#                ↳ 这叫"迁移学习":不在白纸上从零学,
#                  而是在"已经在 80 类日常物体上学过"的基础上继续教。
#                  好处:学得快、小数据也能出效果。
#   epochs  = 100                             把 1620 张图来回看 100 遍
#   imgsz   = 640                             图片缩放成 640×640 再喂进去
#                ↳ 原图只有 200×200!放大是为了让缺陷纹理看得更清楚,
#                  这是工业检测里的常规做法。
#   batch   = 32                              一次同时看 32 张(显存不够就调小)
#                ↳ ⚠️ 下面【速度三件套】里解释为什么是 32 不是默认的 16
#   device  = 0                               用第 0 号显卡(你的 RTX 4060)
#   cache   = True                            把 1800 张图预先读进内存(只占 0.2GB)
#                ↳ ⚠️ 速度三件套之一,效果极大
#   workers = 4                               用几个线程读图(Windows 上 8 个反而慢)
#                ↳ ⚠️ 速度三件套之一
#   name    = "yolov8n_baseline"              结果存到 runs/detect/yolov8n_baseline/
#
# 你要做的:
#   ① 自己写这 3 行(不许抄,写完再对答案):
#         from ultralytics import YOLO
#         model = YOLO("yolov8n.pt")
#         model.train(...)          ← 参数自己填
#   ② 运行它。**确认这三件事**,不然就是在白等:
#         - 屏幕上出现 "Ultralytics ... starting training"
#         - 有 1/100、2/100 这样的进度在往前走
#         - 日志里写着 CUDA:0 (NVIDIA GeForce RTX 4060 Laptop GPU),不是 CPU
#   ③ 开着窗,去干别的(见下面"挂机期间干什么")
#
# ┌──────────────────────────────────────────────────────────────┐
# │ ⚠️⚠️ 训练代码必须包在 if __name__ == "__main__": 里面(Windows 铁律) │
# └──────────────────────────────────────────────────────────────┘
#   2026-10-14 上午实况:直接写 model.train(...) 会立刻报错退出,红字很长,
#   关键两行是:
#       RuntimeError: An attempt has been made to start a new process
#       before the current process has finished its bootstrapping phase.
#       ... you have forgotten to use the proper idiom in the main module:
#               if __name__ == '__main__':
#
#   为什么?—— 因为 Windows 开子进程的方式叫 **spawn**(和 Linux 的 fork 不同):
#
#     ① 主进程要开 4 个"读图小工"(workers=4),Windows 的做法是:
#        【重新启动一份 Python,再把你的主文件重新"导入"一遍】,让小工在
#        新进程里干活。
#     ② 问题来了:你的主文件一旦被"导入",里面那行 model.train(...) 就又
#        被执行一次 → 又去开 4 个小工 → 又导入主文件……**无限套娃**。
#     ③ Python 只好中途拦下来报错:"你还没准备好就被重新启动了"。
#
#   修法(就加一层缩进):
#
#       if __name__ == "__main__":      # ← 加这一行
#           model = YOLO("yolov8n.pt")  # ← 下面所有代码缩进 4 格
#           model.train(...)
#
#   `__name__` 的含义:一个 py 文件被【直接运行】时,__name__ 等于 "__main__";
#   被【当模块导入】时,__name__ 等于文件名。所以这行的意思是:
#   "只有我是主角时才跑下面这段;我是被小工顺带导入的,就闭嘴别动。"
#
#   在 PyCharm 里怎么加最快:
#       ① 在 model = YOLO(...) 那行上面打一行 if __name__ == "__main__":
#       ② 用鼠标选中从 model = YOLO(...) 到 model.train(...) 结束的整段
#       ③ 按 Tab 键 → 整段一次性右移 4 格
#
#   ⚠️ 为什么上午的"冒烟测试"没报这个错?
#      因为那次我是用 `python -c "..."` 直接喂给解释器的,没有"主文件"可被导入,
#      所以躲过了这一劫。**只要你是"运行一个 .py 文件",就必须加这层保护。**
#
# ┌──────────────────────────────────────────────────────────────┐
# │ 【速度三件套】—— 我实测对比过,别跳,这决定了你要等 2 小时还是 7 小时 │
# └──────────────────────────────────────────────────────────────┘
#   我在你机器上做了两次实测(2026-10-14):
#
#     配置 A(全默认):batch=16, cache=False, workers=8
#        训练循环 102 次迭代用了 148 秒;验证一次 93 秒
#        → 单轮约 4.1 分钟 → 100 轮 ≈ 6.8 小时 ⚠️
#
#     配置 B(速度三件套):batch=32, cache=True, workers=4
#        训练循环 51 次迭代用了 78 秒;验证一次 约 1 秒
#        → 单轮约 2.0 分钟 → 100 轮 ≈ 3.3 小时 ✅
#
#   为什么差这么多?两个原因,分开看:
#     · batch 16→32:迭代次数减半(102→51),GPU 一次算更多,吞吐更高。
#       显存只用到 3.8G / 8G,完全放得下 → 结论:**batch 开大是白赚的**。
#     · cache=True:验证慢的真实原因不是 GPU,是**从硬盘反复读 1800 张小图**。
#       全部塞进内存(只占 0.2GB)之后,验证从 93 秒变成 1 秒 —— 快了 90 倍。
#       100 轮里光验证这一项,就省下 2.5 小时。
#
#   ⚠️ 记住这个思路:训练慢,先分清是"GPU 慢"还是"读盘慢",
#      大多数时候是后者。这也是 10/16 调参那天要用的分析方法。
#
# 【日志怎么看】—— 只要盯 4 个东西
#     Epoch   1/100        现在第几轮
#     GPU_mem  3.8G        显存占用(8G 以内都安全,超了就报 OOM)
#     box_loss             框的位置错了多少     ← 应该一路下降
