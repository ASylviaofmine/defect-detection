# 【任务 2】实验 B2:提高输入分辨率 imgsz 960             ★★★ 必做
# ==============================================================
#
# 等 B1 完全跑完再做这一组。改动只有两处:
#
#     model = YOLO("yolov8n.pt")        # ← 回到小的 n
#     model.train(
#         ...
#         imgsz   = 960,                # ← 640 改成 960(唯一关键改动)
#         batch   = 16,                 # ← 分辨率变大,显存要省着用,batch 减半
#         ...
#         name    = "yolov8n_960",
#     )
#
# 为什么 batch 要减半?
#   batch=32 在 640 时占 3.8G 显存;960 的像素数是 640 的 2.25 倍,
#   同样 batch 会撑爆 8G 显存 → 报 CUDA out of memory。
#   所以降到 16(占约 4.3G),安全。
#
# ⚠️ 如果还是 OOM:batch 再降到 8。显存不够不丢人,会算才是本事。


