# 【任务 3】生成对比表 + 回填 README                      ★★ 推荐
# ==============================================================
#
# 两组实验都跑完后,在终端里执行(我会陪你一起跑):
#
#     python tools/compare_runs.py yolov8n_baseline yolov8s_640 yolov8n_960
#
# 这个脚本会:
#   ① 从三组实验的 results.csv 里读总体指标(最佳轮次 / mAP / P / R / 耗时)
#   ② 用每组的 best.pt 在验证集上重新评估一次,拿到【每一类】的 AP
#   ③ 打印一张 markdown 对比表,并保存到 runs/detect/compare_report.md
#
# 为什么要看"每一类"而不是只看总 mAP?
#   因为我们的靶子是 crazing —— 总 mAP 涨了 0.005 可能是别的类涨的,
#   **只有 crazing 那一行的 AP 从 0.465 涨上去,才说明药吃对了。**
#
# 判断标准(先想好,免得看到数字才找理由):
#   · crazing AP 明显上升(比如 0.465 → 0.55+)= 方向对了,可以写进文书
#   · crazing AP 没动,别的类涨了 = 换了个路子再试
#   · 全都掉了 = 记下来也是结果,说明这条路过不去(诚实记录比漂亮数字值钱)
#
# 最后把结果填进 README 的 §4.2 表格 Run B 那一行,并把今天写进 §7 日志。


